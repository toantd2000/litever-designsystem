package vn.io.litever.designsystem.theme

import androidx.compose.material.icons.Icons

/**
 * LiteverIcons now serves as an alias for Material Icons.
 * This exposes all Material icons automatically while still allowing us to swap the
 * underlying implementation later if needed.
 */
object LiteverIcons {
    val Rounded = Icons.Rounded
    val Filled = Icons.Filled
    val Outlined = Icons.Outlined
    val TwoTone = Icons.TwoTone
    val Sharp = Icons.Sharp
    val AutoMirrored = Icons.AutoMirrored
}
